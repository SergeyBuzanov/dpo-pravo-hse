'use strict';

/**
 * Мишени касания 44px на ВНУТРЕННИХ страницах (владелец 09.09.2026).
 *
 * На лендинге мишени добирали 20.08.2026, дальше работа не пошла. Замер
 * хит-тестом на 390px показал, чего не хватает: плашка шапки 30–35px,
 * «← Главная» 19px, «Программы» 19px, ссылки подвала 18px, кнопка
 * vi-режима 41px, ссылки блока «Куда ещё можно зайти» на 404 – 20px.
 *
 * Мерить надо хит-тестом, а не высотой бокса: у части ссылок мишень
 * добирается отступом или псевдоэлементом, и бокс врёт в обе стороны.
 *
 * Приём разный по МЕСТУ, и тест держит именно его:
 *   - в ШАПКЕ – отступ с обратным полем: min-height растил липкую шапку
 *     каталога со 109 до 134px на телефоне, а отступ попадает в мишень и
 *     возвращается обратным полем, раскладка не двигается. Величина
 *     отступа считается от высоты бокса: плашка 30–35px, ссылки 19–28px,
 *     поэтому значения разные. Меняется кегль – замер повторить;
 *   - в ПОДВАЛЕ и в списке 404 – min-height: там рост по вертикали
 *     безвреден, а перекрытия быть не должно;
 *   - шаг между ссылками подвала обязан быть НЕ МЕНЬШЕ мишени: две
 *     мишени по 44px при шаге 36px перекрываются, и нижняя ссылка
 *     забирает часть мишени верхней. Поэтому row-gap снят в ноль, а
 *     column-gap оставлен прежним – в строку на широком экране ссылки
 *     стоят как стояли.
 *
 * Ссылки ВНУТРИ текста (адрес почты в «Контактах» политики, ссылки в
 * таблице рейтингов) не добираются намеренно: WCAG 2.5.5 выводит из-под
 * правила строчную ссылку в предложении, а растянутая мишень там
 * перекрыла бы соседние строки.
 */

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');

/** Правило целиком по имени селектора (стили страниц лежат по-разному). */
function rule(src, selector) {
  const re = new RegExp(selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{[^}]*\\}');
  const m = src.match(re);
  assert.ok(m, `правило ${selector} пропало`);
  return m[0];
}

const T44 = /min-height:\s*44px/;

/** Добор отступом: padding N и обратное поле -N в паре, иначе раскладка уедет. */
function pad(src, selector, n) {
  const r = rule(src, selector);
  assert.match(r, new RegExp(`padding:\\s*${n}px 0`), `${selector}: мишень больше не добирается отступом`);
  assert.match(r, new RegExp(`margin:\\s*-${n}px 0`), `${selector}: обратное поле снято – раскладка поедет`);
}

test('каталог: плашка, «← Главная» и ссылки подвала – 44px', () => {
  const src = read('Каталог программ.html');
  pad(src, '.logo', 5);
  pad(src, 'header a.back', 13);
  assert.match(rule(src, '.footer-links a'), T44, 'ссылки подвала каталога мельче мишени');
  assert.match(rule(src, '.footer-links'), /row-gap:\s*0/, 'при шаге меньше 44px мишени подвала перекроются');
  assert.match(src, /<span class="footer-links">/, 'подвал каталога снова собран инлайновым стилем');
  // Отметка «Сравнить» добирает мишень псевдоэлементом. При -8px выходило
  // 44,5px и на части карточек округлялось до 43 – держим -9px.
  assert.match(read('js/compare.js'), /inset:-9px -6px/, 'мишень «Сравнить» вернулась к порогу');
});

test('страницы программ: плашка, «Программы» и подвал – 44px', () => {
  const src = read('scripts/build-program-pages.js');
  pad(src, '.logo', 5);
  pad(src, '.nav-link', 13);
  pad(src, '.crumbs a', 13);
  assert.match(rule(src, '.footer-links a'), T44, 'ссылки подвала страниц программ мельче мишени');
  assert.match(rule(src, '.footer-links'), /row-gap:\s*0/, 'при шаге меньше 44px мишени подвала перекроются');
  // Сгенерированный файл обязан совпадать с генератором: правится генератор.
  const css = read('programs/program.css');
  pad(css, '.logo', 5);
});

for (const page of ['privacy.html', 'ratings.html']) {
  test(`${page}: плашка, кнопка vi-режима, «← На главную» и подвал – 44px`, () => {
    const src = read(page);
    pad(src, '.logo', 7);
    assert.match(rule(src, '.vi-btn'), T44, 'кнопка режима для слабовидящих мельче мишени');
    pad(src, 'header a.back', 8);
    assert.match(rule(src, 'footer a'), T44, 'ссылки подвала мельче мишени');
  });
}

test('404: плашка, «← На главную», список «Куда ещё» и подвал – 44px', () => {
  const src = read('404.html');
  pad(src, '.logo', 5);
  pad(src, '.back', 11);
  assert.match(rule(src, '.elsewhere li a'), T44, 'ссылки «Куда ещё можно зайти» мельче мишени');
  assert.match(rule(src, 'footer a'), T44, 'ссылка подвала 404 мельче мишени');
});
