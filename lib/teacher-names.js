/**
 * Канонические написания имён преподавателей.
 *
 * Источник (карточки программ на hse.ru) пишет одних и тех же людей
 * по-разному: «Максимов Дмитрий Михайлович» на одной странице и
 * «Дмитрий Максимов» на другой. Пока данные зависели от написания,
 * подписи на карточках «плавали» в зависимости от порядка программ
 * (находка аудита 18.08.2026, раздел «Преподаватели»).
 *
 * Правило то же, что у карты выверенных должностей в build-landing.js:
 * данные каталога перезаписывает update-catalog, поэтому канон живёт
 * в коде и применяется при КАЖДОЙ сборке. Записывать сюда можно только
 * пары, проверенные руками: склеить однофамильцев хуже, чем показать
 * человека дважды.
 */

'use strict';

/** Короткое написание -> каноническое (как на личной странице hse.ru). */
const CANONICAL_TEACHER_NAMES = Object.freeze({
  'Дмитрий Максимов': 'Максимов Дмитрий Михайлович',
  'Руслан Будник': 'Будник Руслан Александрович',
});

/** Возвращает каноническое написание имени (или исходное, если канона нет). */
function canonicalTeacherName(name) {
  const key = String(name || '').replace(/\s+/g, ' ').trim();
  return CANONICAL_TEACHER_NAMES[key] || key;
}

module.exports = { CANONICAL_TEACHER_NAMES, canonicalTeacherName };
