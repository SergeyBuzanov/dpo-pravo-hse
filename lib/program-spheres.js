/** Сфера программы или null, если ни один фрагмент не подошёл. */
function sphereOf(program) {
  const title = String(program?.title || '').toLowerCase();
  for (const sphere of SPHERES) {
    if (sphere.match.some((frag) => title.includes(frag.toLowerCase()))) return sphere;
  }
  return null;
}

/**
 * Раскладывает программы по сферам.
 * Возвращает { spheres: [{...sphere, items}], unassigned }.
 * Нераспределённые не теряются молча — вызывающая сторона обязана
 * о них сообщить, иначе витрина соврёт о размере портфеля.
 */
function groupBySphere(programs) {
  const buckets = new Map(SPHERES.map((s) => [s.id, { ...s, items: [] }]));
  const unassigned = [];
  for (const p of programs) {
    const sphere = sphereOf(p);
    if (sphere) buckets.get(sphere.id).items.push(p);
    else unassigned.push(p);
  }
  // Внутри сферы держим порядок фрагментов, а не порядок каталога.
  for (const bucket of buckets.values()) {
    bucket.items.sort((a, b) => {
      const idx = (p) =>
        bucket.match.findIndex((f) => String(p.title).toLowerCase().includes(f.toLowerCase()));
      return idx(a) - idx(b);
    });
  }
  return { spheres: [...buckets.values()], unassigned };
}

/** «6 программ» / «4 программы» / «1 программа». */
function pluralPrograms(n) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return `${n} программа`;
  if ([2, 3, 4].includes(mod10) && ![12, 13, 14].includes(mod100)) return `${n} программы`;
  return `${n} программ`;
}

