'use strict';

/**
 * Подписи пометок-овалов на карточках программ (каталог и «Топ-5»):
 * тип итогового документа, формат обучения и тексты подсказок при
 * наведении. Введены по указанию заказчика 02.09.2026: в овале пишется
 * ТИП (ПК, ПП, Диплом о высшем образовании, Свидетельство об обучении),
 * а расшифровка уходит в подсказку.
 *
 * Модуль общий для update-catalog.js и scripts/build-landing.js – чтобы
 * каталог и главная не разъезжались в формулировках.
 */

/**
 * Пометка итогового документа по типу программы.
 *
 * Сейчас в каталоге только ПК и ПП; «Диплом о высшем образовании» и
 * «Свидетельство об обучении» – типы, названные заказчиком на будущее
 * (второе высшее и программы без итоговой аттестации), ловятся по
 * ключевым словам в названии типа. Незнакомый тип показывается как
 * пришёл, без подсказки – это честнее, чем угадывать документ.
 */
function docBadge(type) {
  const s = String((type && (type.shortTitle || type.title)) || '').trim();
  if (s === 'ПК') {
    return {
      label: 'ПК',
      tip: 'Повышение квалификации. Итоговый документ – удостоверение о повышении квалификации НИУ ВШЭ.',
    };
  }
  if (s === 'ПП') {
    return {
      label: 'ПП',
      tip: 'Профессиональная переподготовка. Итоговый документ – диплом о профессиональной переподготовке НИУ ВШЭ.',
    };
  }
  if (/высш/i.test(s)) {
    return {
      label: 'Диплом о высшем образовании',
      tip: 'Итоговый документ – диплом о высшем образовании.',
    };
  }
  if (/свидетельств/i.test(s)) {
    return {
      label: 'Свидетельство об обучении',
      tip: 'Итоговый документ – свидетельство об обучении.',
    };
  }
  return s ? { label: s, tip: '' } : null;
}

/**
 * Формат без пояснения в скобках: «Гибридный (обучение проходит очно и
 * параллельно в онлайн)» в овал не помещается – пояснение уходит в
 * подсказку formatTip.
 */
function shortFormat(title) {
  return String(title || '').replace(/\s*\(.*\)\s*$/, '');
}

/**
 * Подсказка к формату. Порядок проверок важен: составные названия
 * содержат слово «онлайн», поэтому гибрид и смешанный ловятся раньше.
 */
function formatTip(title) {
  const s = String(title || '');
  if (/гибрид/i.test(s)) {
    return 'Занятия проходят очно и параллельно транслируются онлайн – способ участия можно выбирать.';
  }
  if (/смешан/i.test(s)) return 'Часть занятий проходит очно, часть – онлайн.';
  if (/онлайн/i.test(s) && /асинхрон/i.test(s)) {
    return 'Занятия в записи: материалы проходят в удобное время, без привязки к расписанию.';
  }
  if (/онлайн/i.test(s) && /синхрон/i.test(s)) {
    return 'Занятия идут онлайн в реальном времени, по расписанию, с преподавателем.';
  }
  if (/онлайн/i.test(s)) return 'Занятия проходят онлайн.';
  if (/очн/i.test(s)) return 'Занятия проходят очно, в аудиториях факультета права НИУ ВШЭ в Москве.';
  return '';
}

module.exports = { docBadge, shortFormat, formatTip };
